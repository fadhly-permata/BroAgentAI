// Generate extension/src/codicons.ts from the @vscode/codicons SVG sources.
// Run after changing NAMES or bumping @vscode/codicons: node scripts/gen-codicons.mjs
//
// Only the glyphs the panel uses are inlined, so the extension ships no icon
// font and needs no network. Codicons (c) Microsoft, licensed CC-BY-4.0.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'extension', 'package.json'));
const pkgDir = path.dirname(require.resolve('@vscode/codicons/package.json'));
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const iconDir = path.join(pkgDir, 'src', 'icons');

const NAMES = [
  // Activity bar
  'home', 'files', 'search', 'source-control', 'terminal', 'robot', 'info', 'settings-gear',
  // Toolbar and list actions
  'refresh', 'collapse-all', 'new-file', 'new-folder', 'eye', 'add', 'remove', 'close', 'trash',
  'clear-all', 'discard', 'diff', 'go-to-file', 'copy', 'cloud-download', 'arrow-down', 'arrow-up',
  'check', 'chevron-right', 'chevron-down', 'ellipsis', 'play', 'debug-stop', 'debug-restart',
  'warning', 'error', 'pulse', 'git-branch', 'folder', 'folder-opened', 'file', 'window', 'regex',
  'case-sensitive', 'circle-filled', 'loading',
];

const out = [];
for (const name of NAMES) {
  const svg = fs.readFileSync(path.join(iconDir, `${name}.svg`), 'utf8');
  const box = /viewBox="0 0 ([0-9]+) ([0-9]+)"/.exec(svg);
  if (!box || box[1] !== box[2]) throw new Error(`${name}.svg has no square viewBox`);
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
  out.push(`  '${name}': [${box[1]}, '${body.replace(/'/g, "\\'")}'],`);
}

const file = `// GENERATED by scripts/gen-codicons.mjs from @vscode/codicons ${version} - do not edit.
// Codicons (c) Microsoft Corporation, licensed CC-BY-4.0:
// https://github.com/microsoft/vscode-codicons
// Each entry is [viewBox size, inner SVG markup]; glyphs draw with fill="currentColor".

export const CODICONS: Record<string, readonly [number, string]> = {
${out.join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'extension', 'src', 'codicons.ts'), file);
console.log(`codicons.ts: ${NAMES.length} glyphs from @vscode/codicons ${version}`);
